"""Markdown tables of the final models against the fixed opponents, aggregated over seeds.

Reads results/summary_final.csv (written by plots/plot_results.py) and writes
results/summary_heuristics.md.

Usage:  python3 -I plots/plot_results.py && python3 -I src/make_tables.py
"""
import csv
from collections import defaultdict
from datetime import date

MAIN = [("r0", "R0, terminal reward"), ("r0_sched", "R0 Sched, entropy 0.1→0"),
        ("r1", "R1, guard break"), ("r2", "R2, potential-based shaping"),
        ("r3", "R3, time-scaled win"), ("r0_floor", "R0 + advantage-std floor"),
        ("r1_floor", "R1 + advantage-std floor")]
ABLATIONS = [("r0_lam0", "λ = 0"), ("r0_lam1", "λ = 1"), ("r0_gamma099", "γ = 0.99"),
             ("r0_charge", "special charge actions"), ("r0_delay0", "action delay 0"),
             ("r0_delay12", "action delay 12")]
OPPONENTS = [("random", "Random"), ("noop", "No-op"), ("back", "Back"), ("footsies_bot", "FootsiesBot")]


def f2(x):
    return f"{float(x):.2f}"


def opponent_table(rows, opp):
    lines = ["| Variant | Seeds | Win (worst–best seed) | Draw | Loss |", "| --- | --- | --- | --- | --- |"]
    for key, name in MAIN:
        r = rows.get(key, {}).get(opp)
        if r is None:
            continue
        lines.append(f"| {name} | {r['seeds']} | **{f2(r['win_mean'])}** ({f2(r['win_min'])}–{f2(r['win_max'])}) "
                     f"| {f2(r['draw_mean'])} | {f2(r['loss_mean'])} |")
    return "\n".join(lines)


def ablation_table(rows):
    head = "| Variant (1 seed) | " + " | ".join(f"{n}<br>W / D / L" for _, n in OPPONENTS) + " |"
    lines = [head, "| --- |" + " --- |" * len(OPPONENTS)]
    for key, name in ABLATIONS:
        if key not in rows:
            continue
        cells = []
        for o, _ in OPPONENTS:
            r = rows[key].get(o)
            cells.append("–" if r is None else
                         f"**{f2(r['win_mean'])}** / {f2(r['draw_mean'])} / {f2(r['loss_mean'])}")
        lines.append(f"| {name} | " + " | ".join(cells) + " |")
    return "\n".join(lines)


def main():
    rows = defaultdict(dict)
    for r in csv.DictReader(open("results/summary_final.csv")):
        rows[r["variant"]][r["opponent"]] = r
    sections = "\n\n".join(f"### Against {name}\n\n{opponent_table(rows, o)}" for o, name in OPPONENTS)
    text = f"""# Final models against the fixed opponents

Generated by `src/make_tables.py` on {date.today().isoformat()} from `results/summary_final.csv`.

Each final model (20M training steps) plays 100 games against each fixed opponent, with a stochastic
policy and sides P1/P2 alternated. All numbers are **shares of games, from the trained agent's point of
view**:

- **Win**: the agent knocks out the opponent.
- **Draw**: neither player is knocked out within 4000 steps (timeout).
- **Loss**: the agent is knocked out.

Win + Draw + Loss = 1 for each model. For the 5-seed variants the values are means over seeds; for wins
the worst and best seed are given in brackets.

## Reward variants (5 seeds each)

{sections}

## Ablations on R0 (1 seed, descriptive)

Each cell is **Win** / Draw / Loss.

{ablation_table(rows)}

## How to read the tables

- Random and FootsiesBot measure strength: the bot is the only fixed opponent that attacks.
- No-op and Back are passive: almost every final model draws all its games against them. Against No-op,
  the 5M-step checkpoints won on average 60–100% of the games (see `results/figures/report_noop.png`).
- With 5 seeds the smallest detectable difference between two means is about 0.3: two variants can only
  be told apart when their worst–best ranges are clearly separated.
"""
    open("results/summary_heuristics.md", "w").write(text)
    print("saved results/summary_heuristics.md")


if __name__ == "__main__":
    main()
